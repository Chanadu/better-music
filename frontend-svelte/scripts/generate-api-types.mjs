import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const swaggerPath = fileURLToPath(new URL('../../backend/docs/swagger.json', import.meta.url));
const outputPath = fileURLToPath(new URL('../src/lib/scripts/api-types.ts', import.meta.url));

const check = process.argv.includes('--check');
const { definitions = {} } = JSON.parse(await readFile(swaggerPath, 'utf8'));

const typeName = (reference) => reference.split('/').at(-1).split('.').at(-1);

const toTypeScript = (schema) => {
	if (!schema) return 'unknown';
	if (schema.$ref) return typeName(schema.$ref);
	if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');

	switch (schema.type) {
		case 'array':
			return `${toTypeScript(schema.items)}[]`;
		case 'boolean':
			return 'boolean';
		case 'integer':
		case 'number':
			return 'number';
		case 'object': {
			if (schema.additionalProperties) {
				return `Record<string, ${toTypeScript(schema.additionalProperties)}>`;
			}

			return 'Record<string, unknown>';
		}
		case 'string':
			return 'string';
		default:
			throw new Error(`Unsupported Swagger schema: ${JSON.stringify(schema)}`);
	}
};

const renderDefinition = ([qualifiedName, schema]) => {
	const name = typeName(qualifiedName);
	const required = new Set(schema.required ?? []);
	const properties = Object.entries(schema.properties ?? {});

	if (schema.type !== 'object' || properties.length === 0) {
		return `export type ${name} = ${toTypeScript(schema)};`;
	}

	const fields = properties.map(
		([propertyName, propertySchema]) =>
			`\t${propertyName}${required.has(propertyName) ? '' : '?'}: ${toTypeScript(propertySchema)};`,
	);

	return [`export type ${name} = {`, ...fields, '};'].join('\n');
};

const generated = [
	'// Generated from backend/docs/swagger.json by scripts/generate-api-types.mjs.',
	'// Do not edit this file directly. Run `npm run api:types` instead.',
	'',
	...Object.entries(definitions)
		.sort(([first], [second]) => first.localeCompare(second))
		.flatMap((definition) => [renderDefinition(definition), '']),
].join('\n');

if (check) {
	const current = await readFile(outputPath, 'utf8').catch(() => '');

	if (current !== generated) {
		console.error('API types are out of date. Run `npm run api:types`.');
		process.exit(1);
	}
} else {
	await writeFile(outputPath, generated);
}
